//go:build ignore

// Run this generator on Windows from internal/scan.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"

	"golang.org/x/sys/windows"
)

func main() {
	upcase := windows.NewLazySystemDLL("ntdll.dll").NewProc("RtlUpcaseUnicodeChar")
	if err := upcase.Find(); err != nil {
		panic(err)
	}
	var offsets [0x10000]int
	for code := range offsets {
		mapped, _, _ := upcase.Call(uintptr(code))
		offsets[code] = int(uint16(mapped)) - code
	}

	var source bytes.Buffer
	fmt.Fprintln(&source, "// Code generated by windowscasegen/main.go; DO NOT EDIT.")
	fmt.Fprintln(&source, "\npackage scan")
	fmt.Fprintln(&source, "\nvar windowsUpperRanges = [...]windowsUpperRange{")
	for first := 0x80; first < len(offsets); {
		offset := offsets[first]
		if offset == 0 {
			first++
			continue
		}
		last, stride := first, 1
		if first+2 < len(offsets) && offsets[first+1] == 0 && offsets[first+2] == offset {
			stride = 2
		}
		for last+stride < len(offsets) && offsets[last+stride] == offset &&
			(stride == 1 || offsets[last+1] == 0) {
			last += stride
		}
		fmt.Fprintf(&source, "\t{0x%04x, 0x%04x, %d, %d},\n", first, last, stride, offset)
		first = last + 1
	}
	fmt.Fprintln(&source, "}")
	formatted, err := format.Source(source.Bytes())
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("windows_case_table_linux.go", formatted, 0644); err != nil {
		panic(err)
	}
}
